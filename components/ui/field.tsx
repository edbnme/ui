function FieldSeparator({
  children,
  className,
  ...props
}: React.ComponentProps<"div"> & {
  children?: React.ReactNode
}) {
  return (
    <div
      data-slot="field-separator"
      data-content={!!children}
      className={cn(
        "relative -my-2 flex h-5 items-center gap-2 text-body group-data-[variant=outline]/field-group:-mb-2",
        className
      )}
      {...props}
    >
      {/* Two lines beside the text instead of one behind it, so the text
          needs no background and works on any surface. */}
      <Separator className="flex-1 data-horizontal:w-auto" />
      {children && (
        <>
          <span
            className="shrink-0 text-muted-foreground"
            data-slot="field-separator-content"
          >
            {children}
          </span>
          <Separator className="flex-1 data-horizontal:w-auto" />
        </>
      )}
    </div>
  )
}

function FieldError({
  className,
  children,
  errors,
  ...props
}: React.ComponentProps<"div"> & {
  errors?: Array<{ message?: string } | undefined>
}) {
  const content = useMemo(() => {
    if (children) {
      return children
    }

    if (!errors?.length) {
      return null
    }

    const uniqueErrors = [
      ...new Map(errors.map((error) => [error?.message, error])).values(),
    ]

    if (uniqueErrors?.length == 1) {
      return uniqueErrors[0]?.message
    }

    return (
      <ul className="ms-4 flex list-disc flex-col gap-1">
        {uniqueErrors.map(
          (error, index) =>
            error?.message && <li key={index}>{error.message}</li>
        )}
      </ul>
    )
  }, [children, errors])

  if (!content) {
    return null
  }

  return (
    <div
      role="alert"
      data-slot="field-error"
      className={cn("text-body text-[color-mix(in_oklch,var(--destructive),black_15%)] dark:text-[color-mix(in_oklch,var(--destructive),white_25%)]", className)}
      {...props}
    >
      {content}
    </div>
  )
}

